// Which special procedure is attached to what, ported from spec_assign.c.
//
// The C attaches a function pointer to a prototype at boot: `mob_index[rnum]
// .func`, `obj_index[rnum].func`, `world[rnum].func`. A special is therefore a
// property of the *prototype*, not of an instance — every shopkeeper of that
// vnum is a shopkeeper — and it is resolved by name here so that the assignment
// table stays data rather than a pile of function references.
//
// Assignment is skipped entirely under --no-specials, which is what the C's
// `-s` does. A vnum in the table that does not exist in the loaded world is
// ignored: the C logs a SYSERR unless it is running a mini-mud, and the shipped
// stock data is missing several of the vnums this tree assigned to.

// SpecAssignment is one row of the table.
type SpecAssignment struct {
	Vnum int32
	Name string
}

